"""Write LICENCES.md: the data licence and the licences of the runtime dependencies.

Run from the monitor folder:  uv run python licences.py
Re-run it whenever the dependencies change. Pass another root package name as an argument
to check a different project (default: monitor).
"""

import sys
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement

DATA_SECTION = """\
## Data

The numbers come from the DSA Transparency Database, run by the European Commission
(https://transparency.dsa.ec.europa.eu). Source of the licence terms:
https://transparency.dsa.ec.europa.eu/page/data-license

- Unless otherwise indicated, content owned by the EU on that website is licensed under
  Creative Commons Attribution 4.0 International (CC BY 4.0). Reuse is allowed if appropriate
  credit is given and changes are indicated.
- The Commission's reuse policy is implemented by the Commission Decision of 12 December 2011
  on the reuse of Commission documents.
- Third-party content may need permission from the rightholders. This project stores only
  aggregated counts (totals per month, platform, country, ground, category, automation and
  action), never single decisions, names or content.
- Changes made by this project: the daily files are aggregated into monthly totals; each
  decision gets one action by a fixed priority (removal, hiding, reduced reach, account
  action, other); a decision that lists several countries is counted once in each country.
  Results from the published aggregates are labelled as such in the report.

How to cite the database in research:

    European Commission-DG CONNECT, 'Digital Services Act transparency database',
    Directorate-General for Communications Networks, Content and Technology, 2023
    https://doi.org/10.2906/134353607485211
"""


def licence_of(dist: metadata.Distribution) -> str:
    """Best short licence label for an installed package."""
    meta = dist.metadata
    expression = (meta.get("License-Expression") or "").strip()
    if expression:
        return expression
    classifiers = [
        c.split("::")[-1].strip()
        for c in meta.get_all("Classifier") or []
        if c.startswith("License ::")
    ]
    if classifiers:
        return "; ".join(classifiers)
    text = (meta.get("License") or "").strip()
    if text and len(text) <= 60 and "\n" not in text:
        return text
    return "see the package's own files (long licence text)" if text else "not stated in metadata"


def runtime_dependencies(root: str) -> list[metadata.Distribution]:
    """All installed packages the root package needs at run time (not dev tools)."""
    seen: dict[str, metadata.Distribution] = {}
    todo = [root]
    while todo:
        name = todo.pop()
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        key = dist.metadata["Name"].lower().replace("_", "-")
        if key in seen:
            continue
        seen[key] = dist
        for line in dist.requires or []:
            req = Requirement(line)
            if req.marker is None or req.marker.evaluate({"extra": ""}):
                todo.append(req.name)
    seen.pop(root.lower().replace("_", "-"), None)
    return sorted(seen.values(), key=lambda d: d.metadata["Name"].lower())


def main() -> None:
    root = sys.argv[1] if len(sys.argv) > 1 else "monitor"
    rows = [
        f"| {d.metadata['Name']} | {d.version} | {licence_of(d)} |"
        for d in runtime_dependencies(root)
    ]
    text = (
        "# Licences\n\n"
        + DATA_SECTION
        + "\n## Software\n\nRuntime dependencies of this project, from the installed package "
        "metadata. Generated by licences.py.\n\n| Package | Version | Licence |\n|---|---|---|\n"
        + "\n".join(rows)
        + "\n"
    )
    Path("LICENCES.md").write_text(text, encoding="utf-8")
    print(f"Wrote LICENCES.md with {len(rows)} packages.")


if __name__ == "__main__":
    main()
